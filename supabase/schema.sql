-- ---------------------------------------------------------------------------
-- Smart Vending Machine Store — PostgreSQL / Supabase schema
-- ---------------------------------------------------------------------------
--
-- You normally do NOT need to run this by hand: when DATABASE_URL is set the
-- application creates these tables on startup (every statement is
-- IF NOT EXISTS) and inserts the 12-product catalogue if the products table
-- is empty.
--
-- Run it in the Supabase SQL editor if you prefer to provision the database
-- yourself, or to inspect what the app creates:
--   Supabase dashboard → SQL Editor → New query → paste → Run.
--
-- Timestamps are stored as TEXT (UTC, 'YYYY-MM-DD HH:MM:SS') rather than
-- timestamptz so that the API payload is byte-for-byte identical to the
-- SQLite backend and the admin dashboard can append " UTC" to the value.
-- ---------------------------------------------------------------------------

BEGIN;

CREATE TABLE IF NOT EXISTS products (
  id                  INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  code                TEXT    NOT NULL UNIQUE,
  name                TEXT    NOT NULL,
  price_paise         INTEGER NOT NULL DEFAULT 0 CHECK (price_paise >= 0),
  stock               INTEGER NOT NULL DEFAULT 0 CHECK (stock >= 0),
  available           BOOLEAN NOT NULL DEFAULT TRUE,
  image               TEXT    NOT NULL DEFAULT '',
  low_stock_threshold INTEGER NOT NULL DEFAULT 5,
  created_at          TEXT    NOT NULL DEFAULT (to_char(now() at time zone 'utc','YYYY-MM-DD HH24:MI:SS')),
  updated_at          TEXT    NOT NULL DEFAULT (to_char(now() at time zone 'utc','YYYY-MM-DD HH24:MI:SS'))
);

CREATE TABLE IF NOT EXISTS transactions (
  id             INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  txn_id         TEXT    NOT NULL UNIQUE,
  created_at     TEXT    NOT NULL DEFAULT (to_char(now() at time zone 'utc','YYYY-MM-DD HH24:MI:SS')),
  product_code   TEXT,
  product_name   TEXT,
  price_paise    INTEGER NOT NULL DEFAULT 0 CHECK (price_paise >= 0),
  inserted_paise INTEGER NOT NULL DEFAULT 0 CHECK (inserted_paise >= 0),
  change_paise   INTEGER NOT NULL DEFAULT 0 CHECK (change_paise >= 0),
  status         TEXT    NOT NULL DEFAULT 'completed'
);

CREATE INDEX IF NOT EXISTS idx_transactions_created_at ON transactions (created_at DESC);

CREATE TABLE IF NOT EXISTS admin_users (
  id            INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  username      TEXT    NOT NULL UNIQUE,
  password_hash TEXT    NOT NULL,
  salt          TEXT    NOT NULL,
  created_at    TEXT    NOT NULL DEFAULT (to_char(now() at time zone 'utc','YYYY-MM-DD HH24:MI:SS'))
);


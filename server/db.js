export function toPublicProduct(row) {
  const threshold = num(row.low_stock_threshold ?? LOW_STOCK_THRESHOLD_DEFAULT);
  const stock = num(row.stock);
  return {
    id: row.id,
    code: row.code,
    name: row.name,
    pricePaise: num(row.price_paise),
    price: num(row.price_paise) / 100,
    stock,
    available: Boolean(row.available),
    lowStock: stock > 0 && stock <= threshold,
    lowStockThreshold: threshold,
    image: row.image || null,
  };
}

export function toPublicTransaction(row) {
  return {
    id: row.id,
    txnId: row.txn_id,
    createdAt: row.created_at,
    productCode: row.product_code,
    productName: row.product_name,
    pricePaise: num(row.price_paise),
    insertedPaise: num(row.inserted_paise),
    changePaise: num(row.change_paise),
    status: row.status,
  };
}


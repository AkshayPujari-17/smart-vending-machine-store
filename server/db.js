/* Stats & history                                                     */
/* ------------------------------------------------------------------ */

export async function getStats(db) {
  const [inventory] = (await db.query(
    'SELECT COUNT(*) AS products, COALESCE(SUM(stock), 0) AS units FROM products'
  )).rows;

  // The transactions table has no quantity column: one row == one unit sold.
  const [sales] = (
    await db.query(
      `SELECT COUNT(*) AS sales,
              COALESCE(SUM(price_paise), 0) AS revenue
       FROM transactions
       WHERE status = 'completed'`
    )
  ).rows;

  const lowStockRows = (
    await db.query(
      'SELECT * FROM products WHERE stock > 0 AND stock <= low_stock_threshold ORDER BY stock, code'
    )
  ).rows;
  const [soldOut] = (await db.query('SELECT COUNT(*) AS n FROM products WHERE stock = 0')).rows;

  const topSellers = (
    await db.query(
      `SELECT product_code AS code, product_name AS name, COUNT(*) AS sold
       FROM transactions
       WHERE status = 'completed' AND product_code IS NOT NULL
       GROUP BY product_code, product_name
       ORDER BY sold DESC, code ASC
       LIMIT 5`
    )
  ).rows.map((r) => ({ code: r.code, name: r.name, sold: num(r.sold) }));

  return {
    totalProducts: num(inventory?.products),
    unitsInStock: num(inventory?.units),
    totalSales: num(sales?.sales),
    productsSold: num(sales?.sales),
    revenuePaise: num(sales?.revenue),
    lowStockCount: lowStockRows.length,
    soldOutCount: num(soldOut?.n),
    topSellers,
  };
}

export async function listTransactions(db, { limit = 50, offset = 0 } = {}) {
  const take = Math.min(500, Math.max(1, Number(limit) || 50));
  const skip = Math.max(0, Number(offset) || 0);

  const [{ total }] = (await db.query('SELECT COUNT(*) AS total FROM transactions')).rows;
  const { rows } = await db.query('SELECT * FROM transactions ORDER BY id DESC LIMIT ? OFFSET ?', [take, skip]);

  return { total: num(total), transactions: rows.map(toPublicTransaction) };
}


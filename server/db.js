export async function createAdminUser(db, { username, passwordHash, salt }) {
  const result = await db.query(
    'INSERT INTO admin_users (username, password_hash, salt) VALUES (?, ?, ?) {{returningId}}',
    [username, passwordHash, salt]
  );
  if (result.rows.length) return result.rows[0].id;
  return lastInsertId(db);
}

export async function updateAdminPassword(db, id, passwordHash, salt) {
  const { rowCount } = await db.query('UPDATE admin_users SET password_hash = ?, salt = ? WHERE id = ?', [
    passwordHash,
    salt,
    id,
  ]);
  return rowCount > 0;
}


/**
 * Data layer.
 *
 * Two interchangeable storage backends behind one small async API:
 *
 *   - SQLite   (Node's built-in `node:sqlite`)  → local development & tests
 *   - Postgres (`pg`)                           → Supabase, or any PostgreSQL
 *
 * `openDatabase()` picks the backend:
 *
 *   1. an explicit `dbPath` option (always wins – the tests rely on it) → SQLite
 *   2. `DB_PATH` in the environment                                     → SQLite
 *   3. `DATABASE_URL` or `SUPABASE_DB_URL`                              → Postgres
 *   4. otherwise `./data/vending.db`                                    → SQLite
 *
 * Responsibilities:
 *  - open the database and make sure the schema + seed catalogue exist
 *  - expose atomic, validated purchase / refund operations
 *  - product, stats, history and admin-user queries used by the dashboard
 *
 * SQL is written once with `?` placeholders and `{{token}}` dialect markers;
 * `renderSql()` (server/sqlDialect.js) adapts it per engine, so store
 * functions never branch on the backend.
 */

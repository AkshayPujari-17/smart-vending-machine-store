/**
 * Open the right database and make sure the schema + seed catalogue exist.
 * @param {{ dbPath?: string, databaseUrl?: string }} [options]
 * @returns {Promise<Db>}
 */
export async function openDatabase(options = {}) {
  // An explicit dbPath always wins, so the test suite keeps its own temp file.
  const explicitPath = options.dbPath || process.env.DB_PATH;
  if (explicitPath) return openSqlite(explicitPath);

  const url = options.databaseUrl || process.env.DATABASE_URL || process.env.SUPABASE_DB_URL;
  if (url) return openPostgres(url);

  return openSqlite(path.join(ROOT_DIR, 'data', 'vending.db'));
}

/** @param {string} dbPath */
async function openSqlite(dbPath) {
  const isMemory = dbPath === ':memory:';
  const location = isMemory ? dbPath : path.resolve(dbPath);
  if (!isMemory) fs.mkdirSync(path.dirname(location), { recursive: true });

  let sqlite;
  try {
    sqlite = new DatabaseSync(location);
  } catch (err) {
    throw new Error(`Cannot open the SQLite database at ${location}: ${err.message}`);
  }

  // SQLite has a single connection, so transactions must not overlap: a naive
  // BEGIN inside another transaction throws. The queue serialises them.
  let txQueue = Promise.resolve();

  const db = {
    kind: 'SQLite',
    location,
    dialect: 'sqlite',

    async query(sql, params = []) {
      const stmt = sqlite.prepare(renderSql('sqlite', sql));
      // node:sqlite only binds null / number / bigint / string / Uint8Array.
      const bound = params.map((p) => (typeof p === 'boolean' ? (p ? 1 : 0) : p));
      // `columns()` reports the result shape: non-empty for SELECT,
      // `INSERT ... RETURNING` and value-returning PRAGMAs, empty otherwise.
      // (The old `reader` flag is gone in current Node builds.)
      if (stmt.columns().length > 0) {
        const rows = stmt.all(...bound);
        return { rows, rowCount: rows.length };
      }
      const info = stmt.run(...bound);
      return { rows: [], rowCount: Number(info.changes) };
    },

    async withTransaction(fn) {
      const run = txQueue.then(async () => {
        sqlite.exec('BEGIN IMMEDIATE');
        try {
          const result = await fn({ dialect: 'sqlite', query: db.query });
          sqlite.exec('COMMIT');
          return result;
        } catch (err) {
          try {
            sqlite.exec('ROLLBACK');
          } catch {
            /* transaction already aborted */
          }
          throw err;
        }
      });
      // Keep the queue alive even when a transaction fails.
      txQueue = run.then(
        () => undefined,
        () => undefined
      );
      return run;
    },

    async close() {
      await txQueue;
      sqlite.close();
    },
  };

  await applySchema(db, SQLITE_DDL);
  try {
    await seedProductsIfEmpty(db);
  } catch (err) {
    // Never leak an open handle – on Windows it keeps the file locked.
    await db.close().catch(() => {});
    throw err;
  }
  return db;
}

/** @param {string} url */
async function openPostgres(url) {
  const db = await createPostgresDriver(url);
  try {
    await applySchema(db, POSTGRES_DDL);
    await seedProductsIfEmpty(db);
  } catch (err) {
    await db.close().catch(() => {});
    throw err;
  }
  return db;
}

/** Run the DDL (idempotent – every statement uses IF NOT EXISTS). */
async function applySchema(db, ddl) {
  if (db.dialect === 'postgres') {
    // The `pg` simple-query protocol accepts multiple statements per call.
    await db.query(ddl);
    return;
  }
  // node:sqlite's exec() runs several statements, but keep them separate so a
  // failure names the statement that broke.
  for (const statement of ddl.split(';')) {
    const sql = statement.trim();
    if (!sql) continue;
    await db.query(sql);
  }
}

/** Insert the default catalogue when the products table is empty. */
async function seedProductsIfEmpty(db) {
  const { rows } = await db.query('SELECT COUNT(*) AS n FROM products');
  if (num(rows[0]?.n) > 0) return 0;

  await db.withTransaction(async (tx) => {
    for (const p of SEED_PRODUCTS) {
      await tx.query(
        `INSERT INTO products (code, name, price_paise, stock, available, image, low_stock_threshold)
         VALUES (?, ?, ?, ?, ?, ?, ?)`,
        [p.code, p.name, p.pricePaise, p.stock, true, `/img/products/${p.code.toLowerCase()}.svg`, LOW_STOCK_THRESHOLD_DEFAULT]
      );
    }
  });
  return SEED_PRODUCTS.length;
}


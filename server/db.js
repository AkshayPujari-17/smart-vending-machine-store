/**
 * Receipt id in the format used by the original data:
 * `TXN-<base36 timestamp>-<6 hex chars>`, e.g. `TXN-MVP6VMZB-885DCB`.
 */
function newTxnId() {
  const stamp = Date.now().toString(36).toUpperCase().padStart(8, '0').slice(-8);
  return `TXN-${stamp}-${crypto.randomBytes(3).toString('hex').toUpperCase()}`;
}

/** Insert and return the new row id on both engines. */
async function lastInsertId(db) {
  const { rows } = await db.query('SELECT last_insert_rowid() AS id');
  return rows[0].id;
}

/**
 * Sell one unit of `code` if the machine can afford it.
 *
 * The whole check-and-decrement runs inside one transaction, and the guard
 * `AND stock > 0` makes the UPDATE itself the authority on availability: two
 * simultaneous purchases can never both succeed and stock never goes negative.
 *
 * @returns {Promise<
 *   | { ok: true, txnId, product, pricePaise, balanceAfter, changePaise, breakdown }
 *   | { ok: false, httpStatus, code, message, requiredPaise?, product? }
 * >}
 */
export async function completePurchase(db, code, balancePaise) {
  const productCode = typeof code === 'string' ? code.trim().toUpperCase() : '';
  if (!productCode) {
    return { ok: false, httpStatus: 404, code: 'INVALID_CODE', message: 'Unknown product code.' };
  }

  return db.withTransaction(async (tx) => {
    const product = await getProductByCode(tx, productCode);
    if (!product) {
      return {
        ok: false,
        httpStatus: 404,
        code: 'INVALID_CODE',
        message: `Product "${productCode}" does not exist.`,
      };
    }

    if (!product.available) {
      return {
        ok: false,
        httpStatus: 409,
        code: 'UNAVAILABLE',
        message: `${product.name} is currently unavailable.`,
        product: toPublicProduct(product),
      };
    }

    if (product.stock <= 0) {
      return {
        ok: false,
        httpStatus: 409,
        code: 'SOLD_OUT',
        message: `Sorry, ${product.name} is sold out.`,
        product: toPublicProduct(product),
      };
    }

    if (balancePaise < product.price_paise) {
      const requiredPaise = product.price_paise - balancePaise;
      return {
        ok: false,
        httpStatus: 402,
        code: 'INSUFFICIENT_BALANCE',
        message: `Please insert ${formatRupees(requiredPaise)} more to buy ${product.name}.`,
        requiredPaise,
        product: toPublicProduct(product),
      };
    }

    // Guarded decrement – the single authority on whether we still had stock.
    const { rowCount } = await tx.query(
      'UPDATE products SET stock = stock - 1, updated_at = {{now}} WHERE id = ? AND stock > 0',
      [product.id]
    );
    if (rowCount === 0) {
      return {
        ok: false,
        httpStatus: 409,
        code: 'SOLD_OUT',
        message: `Sorry, ${product.name} is sold out.`,
        product: toPublicProduct(product),
      };
    }

    const changePaise = balancePaise - product.price_paise;
    const txnId = newTxnId();
    const insert = await tx.query(
      `INSERT INTO transactions (txn_id, product_code, product_name, price_paise, inserted_paise, change_paise, status)
       VALUES (?, ?, ?, ?, ?, ?, ?) {{returningId}}`,
      [txnId, product.code, product.name, product.price_paise, balancePaise, changePaise, 'completed']
    );
    const txnRowId = insert.rows.length ? insert.rows[0].id : await lastInsertId(tx);

    const fresh = await getProductById(tx, product.id);
    return {
      ok: true,
      txnId,
      txnRowId,
      product: toPublicProduct(fresh || product),
      pricePaise: product.price_paise,
      balanceAfter: changePaise,
      changePaise,
      breakdown: changeBreakdown(changePaise),
    };
  });
}

/** Record the value of a cancelled transaction (refunded coins). */
export async function recordRefund(db, refundedPaise) {
  if (!isValidPaise(refundedPaise) || refundedPaise <= 0) return null;

  const txnId = newTxnId();
  await db.query(
    `INSERT INTO transactions (txn_id, product_code, product_name, price_paise, inserted_paise, change_paise, status)
     VALUES (?, NULL, ?, 0, ?, ?, ?) {{returningId}}`,
    [txnId, REFUND_LABEL, refundedPaise, refundedPaise, 'cancelled']
  );
  return txnId;
}

